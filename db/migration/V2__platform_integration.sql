-- ---------------------------------------------------------------------
-- 数据源配置（PF-04）：凭据密文只存 AES-GCM 结果，明文不入库
-- ---------------------------------------------------------------------
CREATE TABLE integration_config (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          BIGINT       NOT NULL,
    code               VARCHAR(64)  NOT NULL,
    name               VARCHAR(128) NOT NULL,
    -- REST / DB_VIEW / FILE
    type               VARCHAR(20)  NOT NULL,
    -- REST 地址 / 视图名 / 文件路径（非敏感）
    endpoint           VARCHAR(512),
    -- AES-GCM 密文（v1:<iv>:<ciphertext>），禁止明文
    credentials_cipher TEXT,
    signature_type     VARCHAR(20)  NOT NULL DEFAULT 'NONE',
    ip_allowlist       JSONB        NOT NULL DEFAULT '[]'::jsonb,
    cron_expr          VARCHAR(64),
    enabled            BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by         VARCHAR(64),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by         VARCHAR(64),
    version            BIGINT       NOT NULL DEFAULT 0,
    is_deleted         BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_integration_config UNIQUE (tenant_id, code)
);
CREATE INDEX idx_integration_config_lookup ON integration_config (tenant_id, enabled, type);

ALTER TABLE integration_config ENABLE ROW LEVEL SECURITY;
CREATE POLICY integration_config_tenant_rls ON integration_config
    USING (NULLIF(current_setting('app.tenant_id', true), '')::bigint IS NULL
           OR tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::bigint)
    WITH CHECK (NULLIF(current_setting('app.tenant_id', true), '')::bigint IS NULL
                OR tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::bigint);

-- ---------------------------------------------------------------------
-- 下达结果回写表（PF-04 兜底）：DB 视图适配器的可运行回写载体
-- ---------------------------------------------------------------------
CREATE TABLE integration_writeback (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       NOT NULL,
    biz_type    VARCHAR(64)  NOT NULL,
    biz_key     VARCHAR(128) NOT NULL,
    payload     JSONB        NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_integration_writeback_lookup ON integration_writeback (tenant_id, biz_type, biz_key);

ALTER TABLE integration_writeback ENABLE ROW LEVEL SECURITY;
CREATE POLICY integration_writeback_tenant_rls ON integration_writeback
    USING (NULLIF(current_setting('app.tenant_id', true), '')::bigint IS NULL
           OR tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::bigint)
    WITH CHECK (NULLIF(current_setting('app.tenant_id', true), '')::bigint IS NULL
                OR tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::bigint);

-- ---------------------------------------------------------------------
-- 审计多条件分页加速（PF-03）
-- ---------------------------------------------------------------------
CREATE INDEX idx_audit_log_lookup ON audit_log (tenant_id, action, actor, created_at DESC);

-- ---------------------------------------------------------------------
-- DB 视图兜底读源（PF-04/US-PF04-5）：底层 sales_order 已启用 RLS，
-- 经视图查询仍受 app.tenant_id 约束。
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW v_integration_order_sample AS
SELECT id, tenant_id, order_no, status, created_at
  FROM sales_order
 WHERE is_deleted = FALSE;
