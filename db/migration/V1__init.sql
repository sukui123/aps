CREATE TABLE constraint_rule (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT       NOT NULL,
    code         VARCHAR(128) NOT NULL,
    name         VARCHAR(128) NOT NULL,
    -- HARD / SOFT / PREFERENCE
    level        VARCHAR(16)  NOT NULL,
    enabled      BOOLEAN      NOT NULL DEFAULT TRUE,
    scope_type   VARCHAR(32)  NOT NULL DEFAULT 'GLOBAL',
    scope_id     BIGINT,
    params       JSONB        NOT NULL DEFAULT '{}'::jsonb,
    weight       NUMERIC(12,4) NOT NULL DEFAULT 1,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version      BIGINT       NOT NULL DEFAULT 0,
    is_deleted   BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_constraint_rule UNIQUE (tenant_id, code)
);
CREATE INDEX idx_constraint_rule_lookup ON constraint_rule (tenant_id, enabled, level);

