-- ---------------------------------------------------------------------
-- 集成异步任务 E7 (OR-01/PF-04/PB-04)：替代消息中间件
-- ---------------------------------------------------------------------
CREATE TABLE integration_task (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT       NOT NULL,
    biz_type        VARCHAR(64)  NOT NULL,
    biz_key         VARCHAR(128) NOT NULL,
    idempotency_key VARCHAR(128),
    payload         JSONB        NOT NULL DEFAULT '{}'::jsonb,
    -- PENDING/RUNNING/SUCCESS/FAILED/RETRY/DEAD
    status          VARCHAR(32)  NOT NULL DEFAULT 'PENDING',
    retry_count     INTEGER      NOT NULL DEFAULT 0,
    next_retry_at   TIMESTAMPTZ,
    last_error      TEXT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by      VARCHAR(64),
    version         BIGINT       NOT NULL DEFAULT 0,
    is_deleted      BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_integration_biz UNIQUE (tenant_id, biz_type, biz_key)
);
CREATE UNIQUE INDEX uq_integration_idempotency ON integration_task (idempotency_key) WHERE idempotency_key IS NOT NULL;
