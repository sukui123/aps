-- ---------------------------------------------------------------------
-- 平台域 E7：租户 / RBAC / 审计 / 幂等 / token 黑名单
-- ---------------------------------------------------------------------
CREATE TABLE tenant (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64)  NOT NULL,
    name        VARCHAR(128) NOT NULL,
    enabled     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_tenant_code UNIQUE (code)
);

CREATE TABLE sys_user (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT       NOT NULL,
    username     VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(128),
    status       VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by   VARCHAR(64),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by   VARCHAR(64),
    version      BIGINT       NOT NULL DEFAULT 0,
    is_deleted   BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_sys_user_name UNIQUE (tenant_id, username)
);

CREATE TABLE sys_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       NOT NULL,
    code        VARCHAR(64)  NOT NULL,
    name        VARCHAR(128) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_sys_role_code UNIQUE (tenant_id, code)
);

CREATE TABLE sys_permission (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       NOT NULL,
    code        VARCHAR(128) NOT NULL,
    name        VARCHAR(128) NOT NULL,
    resource    VARCHAR(255),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_sys_permission_code UNIQUE (tenant_id, code)
);

CREATE TABLE sys_user_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT NOT NULL,
    user_id     BIGINT NOT NULL,
    role_id     BIGINT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_user_role UNIQUE (tenant_id, user_id, role_id)
);

CREATE TABLE sys_role_permission (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT NOT NULL,
    role_id      BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_role_permission UNIQUE (tenant_id, role_id, permission_id)
);

CREATE TABLE token_blacklist (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jti         VARCHAR(128) NOT NULL,
    expires_at  TIMESTAMPTZ  NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_token_jti UNIQUE (jti)
);
CREATE INDEX idx_token_blacklist_expires ON token_blacklist (expires_at);

CREATE TABLE audit_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    BIGINT       NOT NULL,
    actor        VARCHAR(64),
    action       VARCHAR(128) NOT NULL,
    target_type  VARCHAR(64),
    target_id    VARCHAR(64),
    before_json  JSONB,
    after_json   JSONB,
    trace_id     VARCHAR(64),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    is_deleted   BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_audit_log_created_at ON audit_log (created_at);

-- ---------------------------------------------------------------------
-- 资源域 E1 (MD-01/02/06/08)
-- ---------------------------------------------------------------------
CREATE TABLE resource (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         BIGINT        NOT NULL,
    code              VARCHAR(64)   NOT NULL,
    name              VARCHAR(128)  NOT NULL,
    -- 车间 / 工作中心 / 设备 / 线体 / 模具 / 班组
    type              VARCHAR(32)   NOT NULL,
    parent_id         BIGINT,
    ability_tags      JSONB         NOT NULL DEFAULT '[]'::jsonb,
    parallelism       INTEGER       NOT NULL DEFAULT 1,
    efficiency_factor NUMERIC(12,4) NOT NULL DEFAULT 1,
    enabled           BOOLEAN       NOT NULL DEFAULT TRUE,
    valid_from        TIMESTAMPTZ,
    valid_to          TIMESTAMPTZ,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by        VARCHAR(64),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_by        VARCHAR(64),
    version           BIGINT        NOT NULL DEFAULT 0,
    is_deleted        BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_resource_code UNIQUE (tenant_id, code)
);
CREATE INDEX idx_resource_parent ON resource (parent_id);
CREATE INDEX idx_resource_type_enabled ON resource (tenant_id, type, enabled);
CREATE INDEX idx_resource_tags_gin ON resource USING GIN (ability_tags);

CREATE TABLE resource_skill (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       NOT NULL,
    resource_id BIGINT       NOT NULL,
    skill       VARCHAR(64)  NOT NULL,
    level       INTEGER      NOT NULL DEFAULT 1,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_resource_skill UNIQUE (tenant_id, resource_id, skill)
);

CREATE TABLE setup_matrix (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         BIGINT        NOT NULL,
    resource_id       BIGINT,
    from_family       VARCHAR(64)   NOT NULL,
    to_family         VARCHAR(64)   NOT NULL,
    setup_minutes     NUMERIC(12,2) NOT NULL DEFAULT 0,
    same_family_exempt BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version           BIGINT        NOT NULL DEFAULT 0,
    is_deleted        BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_setup_matrix UNIQUE (tenant_id, from_family, to_family)
);

CREATE TABLE downtime (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       NOT NULL,
    resource_id BIGINT       NOT NULL,
    start_at    TIMESTAMPTZ  NOT NULL,
    end_at      TIMESTAMPTZ  NOT NULL,
    reason      VARCHAR(128),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_downtime_window ON downtime (tenant_id, resource_id, start_at, end_at);

