CREATE TABLE work_calendar (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       NOT NULL,
    code        VARCHAR(64)  NOT NULL,
    name        VARCHAR(128) NOT NULL,
    time_zone   VARCHAR(64)  NOT NULL DEFAULT 'Asia/Shanghai',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_calendar_code UNIQUE (tenant_id, code)
);

CREATE TABLE shift_template (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       NOT NULL,
    calendar_id BIGINT       NOT NULL,
    name        VARCHAR(64)  NOT NULL,
    -- 当天分钟偏移；days 为 0..6（周日=0）的 JSON 数组
    start_minute INTEGER     NOT NULL,
    end_minute   INTEGER     NOT NULL,
    days         JSONB       NOT NULL DEFAULT '[1,2,3,4,5]'::jsonb,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_shift_calendar ON shift_template (tenant_id, calendar_id);

CREATE TABLE calendar_exception (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       NOT NULL,
    calendar_id BIGINT       NOT NULL,
    day         DATE         NOT NULL,
    -- HOLIDAY / WORKDAY / OVERTIME
    kind        VARCHAR(32)  NOT NULL,
    remark      VARCHAR(255),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_calendar_exception UNIQUE (tenant_id, calendar_id, day)
);

CREATE TABLE resource_calendar_binding (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT      NOT NULL,
    resource_id BIGINT      NOT NULL,
    calendar_id BIGINT      NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    version     BIGINT      NOT NULL DEFAULT 0,
    is_deleted  BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_resource_calendar UNIQUE (tenant_id, resource_id, calendar_id)
);

