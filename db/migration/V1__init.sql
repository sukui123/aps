-- ---------------------------------------------------------------------
-- 计划域 E3 (SC-02~08)：任务表 / 快照 / 版本 / 计划行 / 决策轨迹
-- ---------------------------------------------------------------------
CREATE TABLE scheduling_run (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT        NOT NULL,
    run_no          VARCHAR(64)   NOT NULL,
    mode            VARCHAR(32)   NOT NULL DEFAULT 'FULL',
    -- 参数快照：时间范围/正倒排/冻结区/权重 JSON
    params          JSONB         NOT NULL DEFAULT '{}'::jsonb,
    -- PENDING/RUNNING/SUCCEEDED/FAILED/CANCELLING/CANCELLED
    status          VARCHAR(32)   NOT NULL DEFAULT 'PENDING',
    phase           VARCHAR(64),
    progress        NUMERIC(5,2)  NOT NULL DEFAULT 0,
    engine_version  VARCHAR(64),
    idempotency_key VARCHAR(128),
    triggered_by    VARCHAR(64),
    cancel_flag     BOOLEAN       NOT NULL DEFAULT FALSE,
    started_at      TIMESTAMPTZ,
    finished_at     TIMESTAMPTZ,
    elapsed_ms      BIGINT,
    failure_reason  TEXT,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    created_by      VARCHAR(64),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_by      VARCHAR(64),
    version         BIGINT        NOT NULL DEFAULT 0,
    is_deleted      BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_run_no UNIQUE (tenant_id, run_no)
);
CREATE UNIQUE INDEX uq_run_idempotency ON scheduling_run (idempotency_key) WHERE idempotency_key IS NOT NULL;
CREATE INDEX idx_run_created_at ON scheduling_run (tenant_id, created_at);
CREATE INDEX idx_run_claim ON scheduling_run (tenant_id, status, created_at);

CREATE TABLE plan_snapshot (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       NOT NULL,
    run_id      BIGINT       NOT NULL,
    -- 输入快照 JSONB：订单/资源/日历/规则/权重 + 各版本 id（只增不改）
    snapshot    JSONB        NOT NULL,
    config_version VARCHAR(64),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,
    is_deleted  BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_snapshot_run UNIQUE (tenant_id, run_id)
);

CREATE TABLE plan_version (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           BIGINT       NOT NULL,
    run_id              BIGINT       NOT NULL,
    version_no          VARCHAR(64)  NOT NULL,
    baseline_version_id BIGINT,
