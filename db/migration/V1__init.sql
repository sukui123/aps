CREATE TABLE operation (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT        NOT NULL,
    routing_id      BIGINT        NOT NULL,
    seq             INTEGER       NOT NULL,
    code            VARCHAR(64),
    name            VARCHAR(128)  NOT NULL,
    std_minutes     NUMERIC(12,2) NOT NULL DEFAULT 0,
    setup_minutes   NUMERIC(12,2) NOT NULL DEFAULT 0,
    -- 串/并/汇聚关系：前驱工序 id 数组，P1 可拆为独立关系表
    predecessor_ids JSONB         NOT NULL DEFAULT '[]'::jsonb,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version         BIGINT        NOT NULL DEFAULT 0,
    is_deleted      BOOLEAN       NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_operation_seq UNIQUE (tenant_id, routing_id, seq)
);

CREATE TABLE operation_resource_group (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id         BIGINT       NOT NULL,
    operation_id      BIGINT       NOT NULL,
    resource_group_code VARCHAR(64) NOT NULL,
    ability_tags      JSONB,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version           BIGINT       NOT NULL DEFAULT 0,
    is_deleted        BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_op_group UNIQUE (tenant_id, operation_id, resource_group_code)
